#!/usr/bin/env python3
"""TEMP(wstc-minimal): build the single-file pipeline for the WSTC Dagster.

The WSTC server takes one .py file per upload, so this inlines the real ELMFIRE block
(images/elmfire/elmfire_block.py), the framework's preview code (src/bench/previews.py),
the block's pinned requirements, and a pre-compiled pyretechnics wheel.

    python scripts/build_wstc_minimal.py --me apearce --wheel path/to/pyretechnics-*.whl
    -> deploy/wstc/<me>_bench_minimal.py

Build the wheel once with a C compiler and CPython 3.12 (any Linux x86_64 host):
    python3.12 -m pip wheel --no-deps pyretechnics==2026.10.20 -w wheels/
"""
import argparse
import base64
import io
import lzma
import re
import tarfile
import zipfile
from pathlib import Path

UPLOAD_LIMIT = 1_000_000          # the WSTC server rejects larger files


# shared libraries the pods' slim image lacks (rasterio's wheel links the system expat);
# shipped alongside pyretechnics and found via LD_LIBRARY_PATH
EXTRA_LIBS = [Path("/usr/lib/x86_64-linux-gnu/libexpat.so.1")]


def pack_pyretechnics(wheel: Path) -> str:
    """Compiled modules only (drop .py/.pxd that have a compiled twin), tar + xz + base85:
    ~0.8 MB instead of the wheel's 1.7 MB as base64."""
    with zipfile.ZipFile(wheel) as z:
        names = [n for n in z.namelist() if n.startswith("pyretechnics/")]
        compiled = {Path(n).name.split(".")[0] for n in names if n.endswith(".so")}
        keep = [n for n in names if n.endswith(".so")
                or (n.endswith(".py") and Path(n).stem not in compiled)]
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w") as t:
            files = [(n, z.read(n)) for n in sorted(keep)]
            files += [(f"bench_libs/{lib.name}", lib.resolve().read_bytes()) for lib in EXTRA_LIBS]
            for n, data in files:
                info = tarfile.TarInfo(n)
                info.size = len(data)
                t.addfile(info, io.BytesIO(data))
    return base64.b85encode(lzma.compress(buf.getvalue(), preset=9 | lzma.PRESET_EXTREME)).decode()

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--me", required=True, help="your short name (letters, digits, underscores)")
    ap.add_argument("--wheel", required=True, type=Path)
    a = ap.parse_args()
    if not re.fullmatch(r"[a-z][a-z0-9_]*", a.me):
        ap.error("--me: lowercase letters, digits and underscores only")
    reqs = [l.strip() for l in (ROOT / "images/elmfire/requirements.txt").read_text().splitlines()
            if l.strip() and not l.startswith("#") and not l.startswith("pyretechnics")]
    src = (ROOT / "deploy/wstc/template_minimal.py").read_text()
    for k, v in {
        "__ME__": a.me,
        "__REQUIREMENTS__": repr(reqs),
        "__BLOCK_SOURCE__": repr((ROOT / "images/elmfire/elmfire_block.py").read_text()),
        "__PREVIEW_SOURCE__": repr((ROOT / "src/bench/previews.py").read_text()),
        "__PKG_B85__": pack_pyretechnics(a.wheel),
    }.items():
        src = src.replace(k, v)
    out = ROOT / "deploy" / "wstc" / f"{a.me}_bench_minimal.py"
    out.write_text(src.replace("# GENERATED by", "# GENERATED (do not edit) by", 1))
    size = out.stat().st_size
    print(f"wrote {out.relative_to(ROOT)} ({size:,} bytes; upload limit {UPLOAD_LIMIT:,})")
    if size > UPLOAD_LIMIT:
        raise SystemExit("!! too big for the WSTC upload limit")


if __name__ == "__main__":
    main()
