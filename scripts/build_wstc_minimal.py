#!/usr/bin/env python3
"""TEMP(wstc-minimal): build the single-file pipeline for the WSTC Dagster.

The WSTC server takes one .py file per upload, so this inlines the real ELMFIRE block
(images/elmfire/elmfire_block.py), the framework's preview code (src/bench/previews.py),
the block's pinned requirements, and a pre-compiled pyretechnics wheel.

    python scripts/build_wstc_minimal.py --me apearce --wheel path/to/pyretechnics-*.whl
    -> deploy/wstc/<me>_bench_minimal.py

Build the wheel once with a C compiler and CPython 3.12 (any Linux x86_64 host):
    python3.12 -m pip wheel --no-deps pyretechnics==2026.10.20 -w wheels/
"""
import argparse
import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--me", required=True, help="your short name (letters, digits, underscores)")
    ap.add_argument("--wheel", required=True, type=Path)
    a = ap.parse_args()
    if not re.fullmatch(r"[a-z][a-z0-9_]*", a.me):
        ap.error("--me: lowercase letters, digits and underscores only")
    reqs = [l.strip() for l in (ROOT / "images/elmfire/requirements.txt").read_text().splitlines()
            if l.strip() and not l.startswith("#") and not l.startswith("pyretechnics")]
    src = (ROOT / "deploy/wstc/template_minimal.py").read_text()
    for k, v in {
        "__ME__": a.me,
        "__REQUIREMENTS__": repr(reqs),
        "__BLOCK_SOURCE__": repr((ROOT / "images/elmfire/elmfire_block.py").read_text()),
        "__PREVIEW_SOURCE__": repr((ROOT / "src/bench/previews.py").read_text()),
        "__WHEEL_NAME__": a.wheel.name.replace(".slim", ""),
        "__WHEEL_B64__": base64.b64encode(a.wheel.read_bytes()).decode(),
    }.items():
        src = src.replace(k, v)
    out = ROOT / "deploy" / "wstc" / f"{a.me}_bench_minimal.py"
    out.write_text(src.replace("# GENERATED by", "# GENERATED (do not edit) by", 1))
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
